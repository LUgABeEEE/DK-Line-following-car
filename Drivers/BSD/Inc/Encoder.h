// 增量式正交编码器读取模块
//
// 硬件映射（与 linefllowing_car.ioc 保持一致）：
//   编码器 E1: PB6 = TIM4_CH1, PB7 = TIM4_CH2
//   编码器 E2: PA6 = TIM3_CH1, PA7 = TIM3_CH2
//
// 定时器参数：TIM3 / TIM4 -> PSC = 49, ARR = 65535
//   APB1 分频为 2，定时器时钟自动 x2 = 72MHz
//   计数时钟 = 72MHz / (49+1) = 1.44MHz  ->  可可靠计数的边沿频率上限约 720kHz
//   ARR 取满量程 65535，对应 16 位计数器，溢出前可累计 65535 个计数
//
// 注意：本模块的编号 ENCODER_A / ENCODER_B 与 PWM.h 的 MOTOR_A / MOTOR_B 对应，
//       即同一颗电机的驱动和编码器用同一个编号，方便 PID 里直接配套使用。
//

#ifndef LINEFLLOWING_CAR_ENCODER_H
#define LINEFLLOWING_CAR_ENCODER_H

#include "main.h"

/* ------------------------------------------------------------------------- */
/* 机械参数 —— 必须按你的实际电机和轮子改，否则速度值不准                        */
/* ------------------------------------------------------------------------- */

/* 编码器线数（每转脉冲数，通常标在电机铭牌上，常见 11 / 13 / 20） */
#define ENCODER_PPR                 13.0f

/* 减速比。写在电机型号末尾，比如 "MG513P30" 就是 30 */
/*
 * 减速比 —— 编码器盘所在轴到车轮之间的传动比。
 *
 * 【实测结论：取 1.0】
 *   原来填 30（认为编码器在马达轴上、经过 30:1 减速箱到轮子）。
 *   实测数据推翻了这一点：
 *     目标 30.9 cm/s、占空比 27.6% 时，计数率只有约 60 计数/秒。
 *     若按 30:1 换算 -> 0.58 cm/s，对应输出轴 2.3 RPM，
 *     这在 27.6% 占空比下是不可能的（那是堵转状态）。
 *     按 1:1 换算 -> 17.4 cm/s，才是合理的量级。
 *
 *   说明这个编码器的码盘直接装在【输出轴】上，
 *   减速比已经在码盘之后了，这里不能再乘。
 *
 * 【怎么确认/微调】
 *   跑 100cm 直线，记录里程 d 的增量：
 *     ENCODER_CALIBRATION = 100 / d增量
 *   填到下面的 ENCODER_CALIBRATION，比改减速比更准。
 */
#define ENCODER_GEAR_RATIO          1.0f

/*
 * 车轮直径，单位 mm。拿卡尺量，或用下面的标定方法反推。
 *
 * 实测：48.0mm。
 *
 * ⚠️ 这个值直接决定速度读数的量纲：
 *    每计数距离 = π×D / (线数×倍频×减速比)
 *    从 65mm 改成 48mm 后，同一转速算出的速度会变成原来的 48/65 = 73.8%。
 *
 *    换句话说：改之前显示 30 cm/s 时，车实际只有约 22 cm/s（虚高 35%）。
 *    改之后显示的才是真实速度 —— 同样的目标值会让车跑得更快，
 *    所以第一次试跑请把目标速度调低一些（建议从 15~20 cm/s 起步）。
 */
#define ENCODER_WHEEL_DIAMETER_MM   48.0f

/*
 * 标定技巧：如果速度值整体偏大或偏小，不要去猜直径，直接用比例修正。
 * 例如让车直行 2 秒、实测走了 40cm，而程序算出 44cm，就把下面的系数设成 40.0f/44.0f。
 */
/*
 * 全局距离标定系数。
 *
 * 【实测标定过程】
 *   循迹模式跑 100cm，记录里程 d 的开始/结束值：
 *       开始 d = 0.6 cm   （原始计数 65534 = -2）
 *       结束 d = 52.2 cm  （原始计数 181）
 *       增量   = 51.6 cm，对应原始计数增量 183
 *
 *   程序算出 51.6cm，真实是 100cm，所以：
 *       1.938 = 100 / 51.6
 *
 * 【为什么误差恰好接近 2 倍】
 *   183 计数 / 100cm = 5.46 mm/计数。
 *   按 13 线 × 4 倍频 × 1:1 减速比、48mm 轮子算应该是 2.90 mm/计数。
 *   差了 1.88 倍 ≈ 2，最可能的原因：
 *     编码器实际每转只产生约 26 个计数（13 × 2），而不是 52（13 × 4）。
 *   也就是四倍频其实只有两倍频（可能只有一路信号的两个边沿被计数）。
 *
 *   不影响使用 —— 这个系数把误差全吸收了。
 *   但如果以后发现"低速时测速抖动大"，可以查一下 A/B 两相是否都正常接入
 *   （两相都正常才能用四倍频，分辨率更高）。
 *
 * 【如果换了轮子或编码器】必须重新标定：
 *   跑已知距离 L，记录 d 的增量 Delta：
 *       ENCODER_CALIBRATION_new = 旧值 * L / Delta
 */
/*
 * 全局距离标定系数 = 真实距离 / 程序算出距离。
 *
 * 【本次标定】
 *   100cm 实测 183 个计数。
 *   按 13 线 × 2 倍频 × 1:1、48mm 轮子算：183 × 5.799mm = 106.1cm。
 *   真实是 100cm，所以 100 / 106.1 = 0.943。
 *
 * 这个值接近 1，说明倍频改为 2 之后的模型基本是对的，
 * 剩下 6% 的偏差来自轮径公差、编码器码盘加工误差。
 */
/*
 * 全局距离标定系数 = 真实距离 / 程序算出距离。
 *
 * 【两次标定的数据】
 *   ① 直线跑 100cm（SPEED_TEST）：
 *        计数增量 183  ->  程序算出 106.1cm  ->  系数 0.943
 *   ② 循迹跑 100cm（LINE_FOLLOW）：
 *        计数增量 172  ->  程序算出  99.8cm  ->  系数 1.002
 *
 *   两次差 6%，原因：
 *     - 循迹路径有弯曲，实际走过的距离大于直线 100cm
 *     - 终点判定靠人眼，有 1~2cm 的误差
 *
 *   取两次的平均（约 177 计数 / 100cm）：0.97
 *
 * 【精度要求】
 *   循迹控制用的是灰度位置反馈，不用里程。
 *   这个系数只影响"速度读数的绝对准确度"。
 *   ±5% 的误差完全可以接受，不必追求更高精度。
 */
#define ENCODER_CALIBRATION         0.97f

/* ------------------------------------------------------------------------- */
/* 分轮标定 —— 修正"两轮速度不一致导致直行跑偏"                                 */
/* ------------------------------------------------------------------------- */

/*
 * 每路编码器单独的修正系数，作用在 ENCODER_CALIBRATION 之上。
 *
 * 【什么时候需要改】
 *   两轮目标速度设成一样，实测读数也接近，但车在直道上慢慢往一边偏。
 *   这说明两个编码器的"每计数对应多少毫米"存在微小差异——
 *   闭环把两个"读数"稳住了，但两个"真实速度"并不相等。
 *
 * 【怎么调】
 *   车往【左】偏  ->  A 实际比 B 慢  ->  把 ENCODER_A_FIX 调小
 *   车往【右】偏  ->  A 实际比 B 快  ->  把 ENCODER_A_FIX 调大
 *
 *   调整量建议每次 0.5%~1%（就是 0.995 / 1.005 这种量级）。
 *   可以先只动 A，B 保持 1.0，避免两个都在变搞不清方向。
 *
 * 【原理】
 *   闭环保持的是"读数 = 目标"，而读数 = 真实速度 x 系数。
 *   系数调小 -> 同样的真实速度算出更小的读数 -> PID 加大输出
 *            -> 真实速度提高。
 *   所以"系数调小"等于"让这个轮子跑得更快"。
 *
 * 【注意】
 *   一旦启用循迹（外环 PD），跑偏会被自动纠正，
 *   这里的分轮标定就只影响"开环直行"和"里程计算"的精度了。
 */
/*
 * A 轮的分轮修正系数（出厂默认值）。
 *
 * 【实测标定：0.995】
 *   让车在长直道上跑，反复微调 ENCA 直到走直，最终落在 0.995。
 *
 *   0.5% 的偏差非常小 —— 编码器只有 26 计数/转，量化误差本身就有 2%，
 *   所以这个值基本在噪声范围内，说明两轮的电机和轮胎匹配良好。
 *
 * 【调整方向（和直觉相反，别搞反）】
 *   ENCA 乘在测速结果上：
 *       调大 -> 测得速度变大 -> 速度环压低占空比 -> A 轮变【慢】-> 车往【左】偏
 *       调小 -> A 轮变【快】-> 车往【右】偏
 *
 *   所以：车往左偏 -> 减小 ENCA；车往右偏 -> 加大 ENCA。
 *
 * 【怎么重新标定】
 *   1. SPEED_TEST，TARGET 设 40，在长直道上跑 2 米
 *   2. 观察 d_A 和 d_B 的增量，两者应该相等
 *   3. 按上面的方向每次调 0.01，直到走直
 */
#define ENCODER_A_FIX               0.995f
#define ENCODER_B_FIX               1.0f

/*
 * 运行时可改的分轮修正系数。
 *
 * 上面两个宏只是【上电初值】。实际参与换算的是下面这两个函数维护的
 * 变量，可以在调参界面实时修改，不需要反复编译烧录。
 *
 * 为什么做成运行时可改：
 *   直行跑偏的修正量通常只有 0.3%~1%，靠"改宏->编译->烧录->试跑"
 *   一轮要几分钟，效率太低。做成按键可调后可以边跑边调。
 *
 * 调好后把最终值写回上面两个宏，写死成默认值。
 */
float Encoder_GetFix(uint32_t index);
void  Encoder_SetFix(uint32_t index, float value);

/* x4 模式（TIM1+TI2 双边沿）时为 4，x2 模式（仅 TI1）时为 2 */
/*
 * 边沿倍频数。
 *
 *   4 = 四倍频（A、B 两相的上升沿 + 下降沿都计数）—— 理论分辨率最高
 *   2 = 两倍频（只数一相的两个边沿）
 *   1 = 单倍频
 *
 * 【实测是 2，不是 4】
 *   跑 100cm 实测 183 个计数：
 *     轮子周长 = π × 48 = 150.8mm
 *     每计数距离 = 1000 / 183 = 5.46mm
 *     每转计数 = 150.8 / 5.46 = 27.6 ≈ 26
 *   而 13 线 × 4 倍频应该是 52。26 = 13 × 2，
 *   说明实际只数了一相的边沿 —— 可能 A/B 中有一相信号没到 MCU，
 *   或者定时器实际工作在单通道模式而不是 TI12。
 *
 * 改成 2 之后 ENCODER_CALIBRATION 就能保持在 1.0 附近，
 * 物理含义也更清楚。
 */
#define ENCODER_EDGE_MULTIPLIER     2.0f

/* ------------------------------------------------------------------------- */
/* 换算常量 —— 由上面的机械参数自动推导，一般不用手改                            */
/* ------------------------------------------------------------------------- */

/* 输出轴（轮子）转一圈的计数：线数 x 倍频 x 减速比 */
#define ENCODER_COUNTS_PER_REV      (ENCODER_PPR * ENCODER_EDGE_MULTIPLIER * ENCODER_GEAR_RATIO)

/* 轮子周长，单位 mm */
#define ENCODER_WHEEL_CIRC_MM       (3.14159265f * ENCODER_WHEEL_DIAMETER_MM)

/* 一个计数对应的行驶距离，单位 mm */
#define ENCODER_MM_PER_COUNT        (ENCODER_WHEEL_CIRC_MM / ENCODER_COUNTS_PER_REV * ENCODER_CALIBRATION)

/* ------------------------------------------------------------------------- */
/* 采样参数                                                                    */
/* ------------------------------------------------------------------------- */

/*
 * 速度计算的时间窗口，单位 ms。
 * 这是"分辨率"和"响应速度"的权衡：
 *   窗口太短 -> 低速时 delta 只有几个计数，量化误差大，PID 会抖
 *   窗口太长 -> 速度反馈滞后，PID 响应变慢
 * 10ms 时每个计数约代表 2cm/s；若觉得低速抖动明显，加大到 20~50ms。
 */
#define ENCODER_PERIOD_MS           20U

/* 速度值的一阶低通滤波系数，范围 (0, 1]：越小越平滑但越滞后，1 表示不滤波 */
#define ENCODER_SPEED_FILTER        0.5f

/* 编码器编号（与 PWM.h 的 MOTOR_A / MOTOR_B 一致） */
#define ENCODER_A                   0U      /* E1: PB6/PB7 -> TIM4 */
#define ENCODER_B                   1U      /* E2: PA6/PA7 -> TIM3 */

/* ------------------------------------------------------------------------- */
/* 接口                                                                        */
/* ------------------------------------------------------------------------- */

/*
 * 使能两路编码器计数（内部调用 HAL_TIM_Encoder_Start）。
 * 请在 MX_TIM3_Init() / MX_TIM4_Init() 之后调用一次。
 * 注意：CubeMX 生成代码不会自动启动编码器，漏掉这句计数器会永远为 0。
 */
void Encoder_Init(void);

/*
 * 复位"上次采样值"基准，并把计数器和滤波状态清零。
 * 在开始一次新的速度测量前调用，避免把上电以来的累计计数当成速度。
 */
void Encoder_Reset(void);

/* 读取计数器原始值（0~65535，回绕）。调试和标定时用。 */
uint16_t Encoder_GetCount(uint32_t encoder);

/* 读取自上次调用以来的计数增量，自带 16 位回绕处理。 */
int16_t Encoder_GetDelta(uint32_t encoder);

/* 清空某个编码器的滤波状态（换向、急停后想立刻重新读速度时用）。 */
void Encoder_ResetFilter(uint32_t encoder);

/*
 * 按 ENCODER_PERIOD_MS 计算两轮速度，单位 cm/s，带符号（正转为正）。
 * 调用节奏很关键：必须固定按 ENCODER_PERIOD_MS 的周期调用，
 * 且两次调用之间的时间就是速度的积分窗口。放进一个 20ms 周期的任务里最合适。
 */
void Encoder_UpdateSpeed(void);

/* 取最近一次 Encoder_UpdateSpeed() 算出的速度，单位 cm/s。 */
float Encoder_GetSpeed(uint32_t encoder);

/* 取累计行驶距离，单位 cm，带符号。 */
float Encoder_GetDistance(uint32_t encoder);

/*
 * 自检：阻塞约 6 秒，每 100ms 打印一次两个编码器的原始计数，
 * 最后打印累计变化量。手工拨动轮子即可判断接线和计数方向是否正确。
 * 通过 huart2 输出，波特率需与 MX_USART2_UART_Init() 的配置一致。
 */
void Encoder_TestSequence(void);

#endif //LINEFLLOWING_CAR_ENCODER_H
