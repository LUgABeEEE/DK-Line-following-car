/* 用编译期默认参数初始化，并复位全部运行状态。 */
void LinePD_Init(Line_PD_t *pd);

/* 复位运行状态（清微分历史、丢线计数、输出），参数保持不变。 */
void LinePD_Reset(Line_PD_t *pd);

