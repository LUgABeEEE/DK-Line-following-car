/*
 * ---- ALL：几乎全部通道激活 ----
 *
 * 出现在三种场合：横向黑线、赛道终点标记、传感器悬空（离开赛道）。
 *
 * 【当前设 0：先关掉，等测速时再启用】
 *   关掉之后 ALL 场景只做记录（sc=ALL 仍然可以在串口看到），
 *   不改变车辆行为 —— 车会按正常 PD 继续跑。
 *
 *   这样做的原因：
 *     测速和调循迹参数阶段不希望"某个瞬间全亮"导致车突然停下，
 *     那种停机会掩盖真正的调参效果，也容易误判成故障。
 *
 * 【什么时候改成 1】
 *   等要做"终点自动停车"功能时再开。
 *   启用后注意：赛道上的十字交叉（横向线）也会触发停车，
 *   如果你的赛道有交叉，需要额外用条件区分（目前没有）。
 */
#define LINE_STOP_ON_ALL_BLACK      0

/* 判定 ALL 需要连续多少拍，避免单帧噪声误触发 */
#define LINE_ALL_CONFIRM_CYCLES     2U

/*
 * ---- 角点事件：SIDE（直角）与 FORK（锐角）合并处理 ----
 *
 * 【为什么不再按直角 / 锐角分开处理】
 *   8 路灰度只能看到"某一帧的通道分布"。车走到锐角弯顶点附近时，
 *   同一条黑线会先被探头切成两段（双簇 -> FORK），再随车头前压
 *   并成一片宽黑带（单簇半边占优 -> SIDE），偶尔还会全亮（ALL）。
 *   这三种"场景"是同一个物理事件在不同瞬间的投影，逐帧分类必然
 *   在你一帧我一帧之间来回跳 —— 这就是"直角判断和锐角判断冲突"。
 *
 *   控制器真正需要的只有两件事：
 *       ① 往哪边转（方向，可以锁存）
 *       ② 转多狠（差速限幅 + 减速系数）
 *   所以把 SIDE / FORK 统一成"角点事件"，事件一旦成立就锁存方向、
 *   直到确认出弯才释放。中途无论分类怎么变，转向决策都不再重算。
 *
 * 【调参】
 *   LINE_CORNER_DIFF_BOOST：角点期间允许的差速倍数。越大转得越狠，
 *     但太大会在弯心甩尾。1.35 是当前实车能过的值。
 *   LINE_CORNER_RELEASE_CYCLES：出弯确认拍数，40ms/拍。
 */
#define LINE_CORNER_DIFF_BOOST      1.35f

/* 进入角点事件需要连续多少拍（Gray 已做帧级防抖，这里只需再确认 1 拍） */
#define LINE_CORNER_CONFIRM_CYCLES  1U

/* 连续多少拍回到 LINE 才认为出弯（3 拍 = 120ms，防弯心残留宽黑带误释放） */
#define LINE_CORNER_RELEASE_CYCLES  3U

/*
 * 出弯后方向记忆保留多少拍（40ms/拍）。
 *
 * 【为什么需要】
 *   实测锐角弯常见的时序是：SIDE/FORK -> 短暂 LINE -> 立刻丢线。
 *   3 拍 LINE 就释放角点事件，corner_dir 被清零，
 *   丢线时既没有锁存方向、最后位置又接近 0（车正压在弯心），
 *   只能退回默认方向盲扫 —— 猜对猜错各一半。
 *   保留 15 拍（600ms），让"刚出弯就丢线"这种情况还能用上刚才的方向。
 */
#define LINE_CORNER_DIR_HOLD_CYCLES 15U

/*
 * ---- 锐角弯的"承诺转向" ----
 *
 * 【问题】（实车日志 17:36:53~54）
 *   V 形锐角的顶点处，车要么转不够角度、要么丢线后立刻"看见"了
 *   自己刚走过的那条腿，于是原地停止搜索、顺着旧线往回跑。
 *   探头扫过旧腿的时间往往只有几十毫秒，按现在的"连续 2 拍确认"
 *   就会把它当成找回来了。
 *
 * 【做法】
 *   如果丢线发生在"锐角证据"（FORK 双簇 / ALL 全黑）的角点事件里，
 *   进入搜索后先闭眼朝锁存方向再转这么久（这段时间内看到线也不算数），
 *   把旧腿扫过去，之后才允许重新捕获。
 *
 * 【取值】
 *   搜索转速 = 24 cm/s 原地转，偏航角速度 (24+24)/16cm ≈ 3 rad/s ≈ 172°/s。
 *     400ms ≈ 69°，加上角点判定前 PD 已经转过的角度，足够越过一条旧腿；
 *   调大：更不容易被旧腿骗到，但直角弯可能转过头；
 *   调小：接近旧行为。
 */
/*
 * ---- 方案 C：用编码器做"定角转弯" ----
 *
 * 时间 ≠ 角度：400ms 的闭眼转弯，实际转过的角度取决于电池电压、轮胎
 * 打滑和地面摩擦 —— 这就是"有时转不够、有时转过头"的来源。
 *
 * 现在用两个编码器的测速积分出偏航角：
 *      yaw += (v_right - v_left) / 轮距 × dt
 * 角点事件里记下起始 yaw，转到目标角度再开始找线。
 *
 * 【LINE_ACUTE_TURN_DEG 怎么定】
 *
 * 关键点：这个角度是从【角点事件发生】开始算的，不是从丢线开始。
 * 事件触发时车还看得见线（SIDE/FORK），到真正丢线时已经转掉一部分，
 * 所以"115° 从事件起点算"换算到车身实际转角，已经接近 V 弯的外角。
 *
 * 实车 A/B（同一赛道，2026-10-25）：
 *   q 版 115°：70 个丢线段，平均 0.96s 找回，最长 2.79s，
 *              61% 在 160° 内找回，0 个反向；
 *   r 版 140°：13 个丢线段，平均 1.62s，最长 5.40s ——
 *              多转的 25° 把出弯腿甩到车后，只能继续扫过头再反向扫回来。
 *
 * 所以默认值退回 115°：承诺转向只负责"把进来那条腿甩开"，
 * 剩下十几度交给同方向的搜索扫过去，边扫边认线，比一次转到底更稳。
 *
 * 调法：看 `[PD] ok xxxms y±deg` 里的 y（本次承诺转向实际转过的角度）——
 *   如果反复出现"y 到了 115 还找不到线" -> 加到 125/130；
 *   如果"转过头、反向扫很久" -> 减到 110。
 */
/*
 * 注意：simple 分支把锐角目标角从 115° 降到 95°。
 * 本分支面向的是"只有弧线/直角"的简单赛道（拱形、方形、椭圆），
 * 这类赛道的角点最多 90°，按 115° 转会转过头、把出弯腿甩到车后。
 * V 形锐角（120~140°）请用 main 分支（那里仍是 115°）。
 */
#define LINE_ACUTE_TURN_DEG          95.0f

/*
 * 承诺转向的兜底超时（ms）。
 * 编码器打滑、轮子被卡住时 yaw 不会增长，靠这个超时退出，防止原地转圈。
 */
#define LINE_ACUTE_COMMIT_TIMEOUT_MS 1500U

/*
 * ---- 直角弯（90°）----
 *
 * 赛道里有 90° 直角（方形地图、拱形赛道的两个底角）时，需要的转角
 * 比 V 形锐角小，只需要 90° 左右。
 *
 * 判定依据：
 *   锐角（V 形）—— 事件里出现过 FORK（两条腿分开）或 ALL（整条全黑），
 *                  按 LINE_ACUTE_TURN_DEG 转；
 *   直角         —— 事件是纯 SIDE（线从一侧滑出），且丢线时横向误差
 *                  已经很大（>= LINE_RIGHT_ANGLE_MIN_ERR_CM），
 *                  按 LINE_RIGHT_ANGLE_TURN_DEG 转。
 *
 * 直角不要转太大：转多了出弯腿会落到车身后方，只能靠反向搜索找回来。
 */
#define LINE_RIGHT_ANGLE_TURN_DEG    90.0f
#define LINE_RIGHT_ANGLE_MIN_ERR_CM  1.2f   /* 丢线时误差至少这么大才算直角 */

/*
 * 角点期间遇到 ALL（整片全黑）时，改用锁存方向满舵。
 *
 * 【原因】
 *   8 路全黑时加权质心必然落在阵列正中，error ≈ 0，
 *   PD 会输出 0 差速 —— 车会"直直地"冲出弯心。
 *   此时位置信息已经没有意义，唯一可靠的是事件开始时锁存的方向。
 *
 * 【安全性】
 *   只在角点事件内生效。直线上的横向黑线（终点标记）不满足
 *   corner_active 条件，行为不变。
 */
#define LINE_ALL_AS_CORNER          1

/*
 * 双向扫描。
 *
 * 【为什么需要】
 *   锐角弯丢线时，车往往已经冲过了弯。此时传感器"最后看到线的方向"
 *   会被过冲主导 —— 比如冲过左弯后线落在车的右侧，
 *   于是搜索往右转，正好是弯道外侧，越转越远。
 *
 *   这不是符号写错，而是"跟着最后位置转"这个启发式在急弯里
 *   原理上就不可靠（过冲量可能大于弯道本身的偏转）。
 *
 * 【做法】
 *   先用锁存方向转 LINE_SEARCH_TIMEOUT_MS；
 *   没找到就换成反方向再转同样长时间；
 *   还没找到才停车。
 *
 *   最坏情况耗时翻倍，但无论初始方向猜对猜错，都能覆盖 360°，
 *   一定能扫到线。对锐角弯这种"猜方向本来就不靠谱"的场景，
 *   用时间来换可靠性是值得的。
 *
 * 设 0 则退回单方向搜索（快但方向可能错）。
 */
#define LINE_SEARCH_BIDIRECTIONAL   1

/* ========================================================================= */
/* 车辆几何                                                                    */
/* ========================================================================= */

/*
 * 左右轮中心距（轮距），单位 cm。实测 16.0。
 *
 * 【用途】
 *   差速 -> 偏航角速度的换算：  omega = (v_right - v_left) / TRACK_WIDTH
 *   搜索转角、弯道所需差速等所有转向推算都基于它。
 *
 * 【为什么必须实测】
 *   曾经按 15cm 估算，导致理论转角比实际大 6%（1200ms 算出 220 度，
 *   实际只有 206 度），调整搜索时间时一直在往上加却总差一点。
 *
 * 【当前几何下的换算表】
 *   纯原地转（外侧 +24 / 内侧 -24）：omega = 48/16 = 3.0 rad/s = 172 度/秒
 *   每拍（外环 40ms）转 6.9 度，这是调搜索时间的粒度。
 *
 *     700ms -> 120 度
 *    1000ms -> 172 度
 *    1160ms -> 199 度
 *    1200ms -> 206 度
 *    1240ms -> 213 度
 *    1360ms -> 234 度
 */
#define LINE_TRACK_WIDTH_CM         16.0f

#define LINE_SEARCH_ENABLE          1

/*
 * 搜索最长时间，单位 ms（双向扫描时是【每一段】的时间）。
 *
 * 【当前取值 1200ms = 206 度】（按实测轮距 16cm 计算）
 *
 *   纯原地转（INNER_RATIO=1.0）的偏航角速度
 *       = (24 + 24) / 16cm = 3.0 rad/s = 172 度/秒
 *   每拍（外环 40ms）转 6.9 度 —— 调整的最小粒度。
 *
 *   演进过程（前几个数值是按错误的 15cm 算的，仅供参考趋势）：
 *      700ms  方向对但角度不够
 *     1100ms  还差约 20 度
 *     1240ms  略多，减 10 度
 *     1200ms  当前，实测（轮距 16cm）约 206 度
 *
 * 【调整方法】
 *   目标转角 D（度） -> TIMEOUT_ms = D / 172 * 1000
 *   只能取到 40ms 的整数倍（6.9 度粒度）。
 */
#define LINE_SEARCH_TIMEOUT_MS      1200U

/*
 * 搜索时的外侧轮速度，单位 cm/s。
 * 太快会转得猛、看不清线；太慢传感器采样时线几乎不动。
 * 10~18 之间比较合适。
 */
/*
 * 搜索时的外侧轮速度，单位 cm/s。
 *
 * 【从 14 提到 24 的原因：扫掠时间占了全部延迟的 90%】
 *
 *   直角弯的时间分解（容差 3 拍、轮距 15cm）：
 *     确认丢线      120ms   ( 10% )
 *     原地扫过 90 度 1086ms  ( 90% )  <- 瓶颈在这里
 *     合计          1206ms
 *
 *   偏航角速度 = (外侧 + 内侧反转) / 轮距
 *     14 cm/s -> 83 度/秒  -> 扫 90 度要 1.09 秒
 *     24 cm/s -> 142 度/秒 -> 扫 90 度只要 0.63 秒
 *
 * 【为什么 24 不会"转太快漏掉线"】
 *   以 142 度/秒算，外环 40ms 一拍转 5.7 度。
 *   传感器 49mm 阵列在约 30mm 距离上对应的张角约 78 度，
 *   扫过它需要约 14 个采样点，完全够传感器反应。
 *
 *   如果确实出现"转过去了但没认出来"，先降到 18~20 试试。
 */
#define LINE_SEARCH_SPEED_CMS       24.0f

/*
 * 搜索时内侧轮的反转比例（相对外侧轮速度）。
 * 0 = 内侧轮不转（绕内侧轮转，半径大）
 * 1 = 内外等速反转（绕自身中心原地转）
 *
 * 取 0.55 让转向中心略微偏向内侧轮，转弯半径小但仍有前进分量，
 * 有利于贴着弯道扫到线。
 */
/*
 * 搜索时内侧轮的反转比例（相对外侧轮速度）。
 *
 *   0    = 内侧轮不转 -> 绕内侧轮转，车会往前跑一大圈
 *   0.55 = 内侧轮半速反转 -> 有小幅前进分量（曾经用这个）
 *   1.0  = 内外等速反向 -> 【绕自身中心原地转】
 *
 * 【为什么改成 1.0】
 *   用 0.55 时，车的中心速度 = (外侧 - 内侧)/2 = (24 - 13.2)/2 ≈ 5.4 cm/s
 *   一直在往前爬。转 1.2 秒就爬出去 6cm 多 —— 正好爬到"身后的那条线"上，
 *   于是车头朝后、线在视野里，就沿着线往回跑了。
 *
 *   改成等速反转后，车绕自身中心旋转，位置基本不动，
 *   只改变朝向，不会无意中碰到别的线段。
 */
#define LINE_SEARCH_INNER_RATIO     1.0f

/*
 * 连续多少个外环周期没看到线，才判定为"真丢线"并进入搜索。
 *
 * 【从 3 降到 2 的原因】
 *   每个周期 40ms，3 拍就是 120ms。
 *   这段时间车仍在按原速前进，弦角弯时已经冲出去好几厘米。
 *   降到 2 拍（80ms）能少冲 40ms 的距离。
 *
 * 【为什么不敢降到 1】
 *   灰度偶尔会有单拍抖动（反光、接缝），1 拍就切搜索会误判，
 *   车会在直道上莫名其妙原地打转。2 拍是安全的下限。
 */
#define LINE_LOST_TOLERANCE         2U

/*
 * 丢线超时后是否停车。
 *
 *   1 = 停车（**初次调试务必用这个**）
 *       丢线就停，车不会冲出赛道，你也能立刻发现"传感器没看到线"。
 *
 *   0 = 继续转向搜索
 *       按灰度模块给出的"最后偏离方向"继续满舵前进，尝试找回线。
 *       适合调试完成后的实跑，但线丢得远时车会一直转圈。
 */
#define LINE_STOP_IF_LINE_LOST      1

/* ------------------------------------------------------------------------- */
/* 控制器结构体                                                                */
/* ------------------------------------------------------------------------- */

typedef struct
{
    /* ---- 可调参数 ---- */
    float kp;               /* 比例增益，单位 cm/s 差速量 每 cm 误差          */
    float kd;               /* 微分增益，单位 cm/s 差速量 每 (cm/s) 误差变化率 */
    float base_speed;       /* 基础速度，cm/s                                 */
    float diff_limit;       /* 差速量限幅，cm/s                               */
    float speed_limit;      /* 目标速度限幅，cm/s                             */
    float d_filter;         /* 微分低通系数 (0,1]                             */

    /* ---- 运行状态：由 Init/Reset 维护 ---- */
    float   error;          /* 最近一次误差，cm（左正右负）                   */
    float   last_error;     /* 上一次误差，用于求微分                          */
    float   d_filter_state; /* 微分项滤波状态                                 */
    float   steer;          /* 最近一次差速量，cm/s                           */
    float   speed;          /* 最近一次的目标基础速度，cm/s                   */
    uint8_t straight_ticks; /* 直道连续居中拍数（simple track 直道加速用）             */
    float   speed_boost;    /* 直道加速系数，0 ~ LINE_STRAIGHT_BOOST_MAX              */

    /* ---- 弧线流畅度（线角前馈 + 位置低通）---- */
    float   pos_filter;     /* 低通后的横向位置 cm                                    */
    float   theta_rad;      /* 线在车头下的切线角（rad，低通后）                       */
    float   last_pos_f;     /* 上一拍的滤波位置                                       */
    float   last_dist_cm;   /* 上一拍的两轮平均里程                                   */

    /* 最近 3 个 (位置, 里程) 样本，用最小二乘斜率估 θ，比两点差分抗噪 */
    float   pos_hist[3];
    float   dist_hist[3];
    uint8_t hist_count;

    float   theta_ff;       /* 当前实际叠加的前馈量（经过死区/斜坡/限幅）             */

    /* ---- 比赛自动停车 ---- */
    float   commit_target_deg; /* 本次承诺转向的目标角度（锐角/直角不同）   */
    uint8_t race_enabled;   /* 1 = 自动停车已启用（自适应模式也置 1）                  */
    uint8_t race_phase;     /* 0=等待 1=巡航(已武装) 2=接近 3=已到位                  */
    uint8_t race_pulse;     /* 连续全黑拍数，用来区分"启停线脉冲"和"角点全黑"          */
    float   race_lap_cm;    /* 一圈周长 cm，0 = 关闭自动停车                          */
    float   race_start_cm;  /* 进入循迹时的里程基准                                   */
    float   race_detect_cm; /* 识别到启停线时的里程                                   */

    /*
     * ---- 输出：左右轮的目标速度，cm/s ----
     *
     * 【为什么要在这里存一份，而不是直接调用 Speed_PID_Update】
     *
     *   外环和必须内环跑在不同的周期上：
     *     外环（循迹 PD）  100ms 一次 —— 读传感器、算差速
     *     内环（速度 PID）  20ms 一次 —— 比对编码器、调 PWM
     *
     *   如果外环里直接调 Speed_PID_Update，那么整个系统里
     *   唯一驱动速度环的地方就是外环，速度环也被拖到 100ms，
     *   比设计值慢 5 倍。轮子来不及跟到目标速度，差速就是错的，
     *   循迹会表现为"稍微一点弯就跟不住、直接偏离"。
     *
     *   正确做法：外环只把目标写进这两个字段，
     *   内环节拍每 20ms 读一次并调用 Speed_PID_Update，
     *   两个环各跑各的周期，互不牵制。
     */
    float   left_target;    /* 左轮目标速度，cm/s，由外环写入、内环读取      */
    float   right_target;   /* 右轮目标速度，cm/s                            */
    uint8_t lost_count;     /* 连续丢线周期数                                 */
    uint8_t line_lost;      /* 1 = 本次判定为丢线                             */
    uint16_t search_ms;     /* 已进入搜索状态的累计时间，ms；找到线后清零     */

    /*
     * ---- 搜索方向锁存与趋势判定 ----
     * search_dir    : 进入搜索时锁定的方向（+1 左 / -1 右 / 0 未锁定）
     * recover_count : 连续看到线的周期数，用于确认"真的找回来了"
     */
    int8_t   search_dir;
    uint8_t  recover_count;

    /*
     * ---- 角点事件状态（SIDE 与 FORK 统一处理）----
     *
     * corner_active  : 1 = 正在角点事件中
     * corner_confirm : 进入事件前的连续确认拍数
     * corner_release : 连续回到 LINE 的拍数
     * corner_dir     : 事件内锁存的转弯方向（+1 左 / -1 右 / 0 未定）
     * all_assist     : 上一拍是否处于"全黑满舵"assist 状态（用于抑制微分冲击）
     * all_count      : ALL 场景连续出现拍数（诊断 / 终点确认用）
     * scene_last     : 上一拍的稳定场景，供遥测显示
     */
    uint8_t  corner_active;
    uint8_t  corner_confirm;
    uint8_t  corner_release;
    int8_t   corner_dir;
    /* 方向证据来源：0 = 无，1 = SIDE（哪半边全黑，优先），2 = FORK（另一条腿） */
    uint8_t  corner_dir_src;
    /* 出弯后方向记忆还剩多少拍（见 LINE_CORNER_DIR_HOLD_CYCLES） */
    uint8_t  corner_dir_hold;

    /*
     * ---- 编码器偏航角（方案 C：定角转弯）----
     * yaw_deg       : 累计偏航角，度；左转为正
     * corner_yaw0   : 角点事件开始时的 yaw，用来算"已经转了多少"
     * last_yaw_tick : 上一次积分的 tick，用来取真实 dt
     * commit_active : 1 = 正在执行承诺转向
     * commit_done   : 1 = 本次搜索已经做过承诺转向（避免重复触发）
     */
    float    yaw_deg;
    float    corner_yaw0;
    uint32_t last_yaw_tick;
    uint8_t  commit_active;
    uint8_t  commit_done;
    int8_t   commit_dir;     /* 承诺转向的方向（锁存时固定，防止中途被清） */
    float    last_commit_turn; /* 上次承诺转向实际转过的角度（度，带符号） */
    /* 本次角点事件是否出现过"锐角证据"（FORK / ALL） */
    uint8_t  corner_acute;
    /* 承诺转向剩余时间 ms（兜底超时，见 LINE_ACUTE_COMMIT_TIMEOUT_MS） */
    uint16_t commit_ms;
    uint8_t  all_assist;
    uint8_t  all_count;
    uint8_t  scene_last;
    /* 本次丢线是否已经打印过 "[PD] lost"（避免每 40ms 打一次，见 LinePD.c） */
    uint8_t  lost_announced;

    uint8_t first_run;      /* 首拍标志，避免微分冲击                         */
} Line_PD_t;

