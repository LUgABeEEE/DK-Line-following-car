/* 周期与限幅                                                                  */
/* ------------------------------------------------------------------------- */

/* 外环执行周期，单位 ms。应取 max(灰度模块更新率, 内环周期 x 3) */
/*
 * 外环（循迹 PD）的更新周期，单位 ms。
 *
 * 【从 100ms 降到 40ms 的原因：这是车速的硬上线】
 *
 *   外环每跑一拍，线相对车会移动 v × T 的距离：
 *       v=40 cm/s, T=100ms  ->  每拍移动 4.0cm
 *   而 8 路传感器总跨度只有 49mm（半量程 ±2.0cm）。
 *   也就是说线在一拍之内就跑出了传感器的视野，
 *   采到的误差是滞后的、跳变的 —— 表现为画龙、过弯跟不上。
 *
 *   降速能缓解，但降速就没意义了。真正该做的是【提高采样频率】：
 *       T=40ms, v=40 cm/s  ->  每拍移动 1.6cm，稳稳在量程内
 *
 *   由此得到车速的上限（单拍移动不超过半量程）：
 *       v_max ≈ 2.0cm / T
 *       T=100ms -> 20 cm/s
 *       T= 40ms -> 50 cm/s   <- 现在
 *       T= 30ms -> 67 cm/s
 *
 * 【代价】
 *   - 必须同时把 LINE_MIN_PERIOD_RATIO 降到 2（见该宏说明）
 *   - I2C 读传感器变得更频繁：每拍 2 次事务约 1.5ms，
 *     CPU 占用从 1.5% 升到 3.8%，可以接受
 */
#define LINE_PD_PERIOD_MS           40U

/*
 * 内外环周期比的下限。小于这个值说明外环跑太快，和内环抢执行机会，
 * 表现为整车高频振荡，而且分不清是哪个环的参数不对。
 */
/*
 * 外环周期 / 内环周期 的最小倍数。
 *
 * 内环 20ms，外环 40ms -> 倍数 2，满足要求。
 *
 * 【为什么从 3 放宽到 2】
 *   原值 3 要求外环至少 60ms，那就没法把外环降到 40ms 了。
 *
 *   这个检查的本意是防止"外环比内环快，内环来不及执行目标"。
 *   倍数 2 意味着内环每转 2 圈、外环才更新一次目标，
 *   对串级控制是够用的（理论上 2 是下限，3~5 更理想）。
 *
 *   如果以后内环也提速到 10ms，那么外环可以降到 20~30ms，
 *   倍数依然保持 2 以上。
 */
#define LINE_MIN_PERIOD_RATIO       2U

/* 差速量限幅，单位 cm/s。防"内侧轮反转"导致原地打转 */
/* ========================================================================= */
/* 差速方向开关 —— 只能用实测确定，不能靠推理                                  */
/* ========================================================================= */

/*
 * 差速分配方向。
 *
 * 【原理】
 *   差速驱动要往哪边转，哪边的轮子就要慢下来：
 *       想左转 -> 左轮慢、右轮快
 *       想右转 -> 左轮快、右轮慢
 *
 *   本代码里 steer > 0 表示"线在传感器正方向一侧"。
 *   默认认为正方向就是车的左边，所以 steer > 0 时左轮减速。
 *
 * 【为什么可能需要反过来】
 *   下面两件事代码里看不出来，只要错一个差速就整体反了：
 *     1. 传感器 CH1~CH8 哪一端在车的左边（装反 180 度就镜像）
 *     2. MOTOR_A 物理上到底是左轮还是右轮（取决于电机接线）
 *
 *   表现：车一偏就朝更偏的方向跑，越纠越偏，直接出线。
 *
 * 【怎么确定该用哪个值】
 *   1. 把车放在线上，故意让车头偏到线的右侧
 *      （也就是说，从车头看，线在车身的左边）
 *   2. 进入 LINE FOLLOW，基础速度设低（10~15 cm/s）
 *   3. 观察车头转向：
 *        车向左转（朝线靠）  -> 保持 0
 *        车向右转（远离线）  -> 改成 1
 *
 *   注意：这一步跟 KP/KD 大小无关，只和正负号有关。
 *   即使 KP 很小，转向方向也应该是对的。
 *
 * 【最终取值：0，配合 GRAY_DIR_SIGN = -1】
 *
 *   推导链（全部符号都已实物确认）：
 *     ① CH1(LED1) 在物理最左侧
 *     ② GRAY_DIR_SIGN = -1  ->  线在左时 P > 0（左正右负）
 *     ③ steer = kp × P      ->  线在左时 steer > 0
 *     ④ 差速驱动铁律        ->  向左转必须右轮快
 *     ⑤ 本宏=0 时 DIR=-1    ->  left = base - steer（左轮慢、右轮快）
 *        线在左 -> 左轮慢右轮快 -> 左转 -> 朝线靠  ✅
 *
 *   若把本宏改成 1，上面第 ⑤ 步反过来，车会朝偏离方向转（越纠越偏）。
 *
 *   ⚠️ 这个宏和 GRAY_DIR_SIGN 是【乘性关系】，两个都改等于没改。
 *      排查方向问题时，先确认 GRAY_DIR_SIGN，再确认本宏，一次只动一个。
 */
#define LINE_STEER_REVERSE      0

/*
 * 由上面那个开关推导出的方向系数：
 *   REVERSE=0 -> -1.0f -> left = base - steer （默认）
 *   REVERSE=1 -> +1.0f -> left = base + steer （反向）
 */
#define LINE_STEER_DIR          (((LINE_STEER_REVERSE) != 0) ? (+1.0f) : (-1.0f))

/*
 * 差速量限幅，单位 cm/s。
 *
 * 【从 25 提到 35 的原因】
 *   钝角弯需要更大的差速才能跟上。实测 LBAS=35 时弯道 s 最大只到 11.4，
 *   看起来余量很大；但那是【已经跟上了】的状态，钝角弯的瞬间需要
 *   远超稳态值的差速才能及时把车头拉回来。
 *
 *   按轮距 15cm 估算，v=45、转弯半径 15cm 时需要 22.5 cm/s。
 *   留一倍余量到 35，才有能力应付半径更小的钝角弯。
 *
 * 上限约束：35 < LINE_SPEED_LIMIT(75)，且 base + 35 不能超过内环量程。
 */
#define LINE_DIFF_LIMIT             35.0f

/* 目标速度限幅，单位 cm/s。内环本身也有限幅，这里提前夹一次更安全 */
/*
 * 单轮目标速度上限，单位 cm/s。
 *
 * 【从 60 提到 75 的原因】
 *   base 40 + 差速 25 = 65 > 60，外侧轮一直被夹住，
 *   等于实际差速被悄悄削弱了。提到 75 后 base 40 + 35 = 75 刚好不被夹。
 *
 * 上限约束：必须小于内环的 SPEED_LIMIT_CMS(80)，
 * 否则外环给出的目标会被内环二次限幅，产生不一致。
 */
#define LINE_SPEED_LIMIT            75.0f

/*
 * 弯道减速：误差达到该值时，目标速度降到基础速度的这个比例。
 * 目的是让车在急弯前主动放慢，而不是硬冲出去。
 * 设为 0.0f 表示不减速（全程保持基础速度）。
 */
/*
 * 弯道减速系数：误差达到满量程时，速度降到基础速度的这个比例。
 *
 * 【从 0.55 降到 0.40 的原因】
 *   钝角弯丢线的根源是"来不及" —— 车以 40+ cm/s 冲进弯道，
 *   等误差长起来时线已经跑到视野外了。
 *
 *   这个系数是按 |误差| 线性插值的：
 *     直道 |e|≈0      -> 不减速
 *     |e|=1cm         -> 降到 0.76 倍
 *     |e|=2cm         -> 降到 0.51 倍
 *     满量程 |e|=2.45 -> 降到 0.40 倍  (40 cm/s -> 16 cm/s)
 *
 *   所以缓弯几乎不减速，急弯大幅减速 —— 正是想要的行为。
 *
 * 代价：钝角弯通过速度会明显变慢。想更激进可以回调到 0.45~0.50。
 */
#define LINE_CURVE_SLOW_MIN         0.40f

/* 编译期默认增益 */
/*
 * 外环比例增益，单位 cm/s 差速量 每 cm 误差。
 *
 * 【实测取值 20.0】
 *   一开始按"1cm 误差给 8cm/s"设的，实测偏软、过弯跟不上。
 *   逐步加到 20 之后直道和弯道都明显更稳。
 *
 *   为什么这个值比直觉大：传感器通道间距只有 7mm，
 *   误差的"物理分辨率"很粗，需要较高的增益才能获得足够的转向权限。
 *
 *   配合 LINE_DIFF_LIMIT = 35 时，e 超过 1.75cm 就进入满幅，
 *   相当于"小误差线性、大误差饱和"，对循迹反而很合适。
 */
#define LINE_PD_DFLT_KP             20.0f
/*
 * 外环微分增益，单位 cm/s 差速量 每 (cm/s) 误差变化率。
 *
 * 【实测取值 1.0 —— 不能大】
 *   微分项 = KD × Δe / dt，而 dt = 40ms，所以放大倍数是 1/0.04 = 25 倍！
 *
 *     1mm 的位置抖动（很常见，7mm 间距的量化噪声就有这个量级）：
 *       KD=1 ->  2.5 cm/s  (占差速限幅的  7%，可忽略)
 *       KD=2 ->  5.0 cm/s  (14%)
 *       KD=4 -> 10.0 cm/s  (29%，肉眼可见的抖动)
 *
 *   实测 KD 加到 4 就明显抖，降到 1 后直道很稳。
 *
 * 【外环周期变了要重算】
 *   这个放大倍数 = 1/dt，所以：
 *     周期从 40ms 改成 100ms（dt 变大）-> 同样的 KD 变得温和，可以调大
 *     周期改成 20ms（dt 变小）          -> 同样的 KD 变得更凶，必须调小
 *   改外环周期后如果出现抖动，第一个要怀疑的就是 KD。
 */
#define LINE_PD_DFLT_KD             1.0f
#define LINE_PD_DFLT_BASE_SPEED     30.0f   /* 基础速度 cm/s               */

/*
 * 循迹模式的起步斜坡，单位 cm/s per second。
 *
 * 【为什么必须有】
 *   没有斜坡时，进入 LINE 模式或调大 LBAS 的那一拍，
 *   基础速度会从 0 直接跳到目标值（比如 15 cm/s）。
 *   内环此时误差突然变成 15，P 项和积分一起发力，
 *   电机被瞬间灌入很大的占空比 —— 表现就是"一启动猛窜一下"。
 *
 *   加上斜坡后，基础速度每 100ms 只增加
 *   LINE_SPEED_RAMP_CMS_PER_SEC / 10 cm/s（默认 5 cm/s），
 *   0 到 15 大约需要 300ms，起步是平滑的。
 *
 * 【和 SPEED_TEST 的关系】
 *   SPEED_TEST 有自己的斜坡（SPEED_RAMP_CMS_PER_SEC，按 20ms 节拍），
 *   两者互不影响。
 */
#define LINE_SPEED_RAMP_CMS_PER_SEC  50.0f

/*
 * 微分低通滤波系数 (0,1]。灰度解算出的位置在探头交界处有固有台阶，
 * 不滤波的话 D 项会把台阶当成分辨率极高的真实变化而放大。
 * 但系数太小会让 D 项严重滞后、失去阻尼作用（外环 100ms 周期下尤其明显），
 * 所以取 0.7 而不是更小。
 */
#define LINE_PD_DFLT_D_FILTER       0.7f

/*
 * 丢线容忍的连续周期数。超过之后按着下面两个开关处理。
 * 1 个周期 = LINE_PD_PERIOD_MS。
 */
/* ========================================================================= */
/* 丢线搜索（抛线挽救）                                                        */
/* ========================================================================= */

/*
 * 丢线后是否尝试找回。
 *
 *   1 = 开启搜索：朝最后看到线的方向原地慢转，限时找线
 *   0 = 丢线立即停车（最保守，但没有任何挽救机会）
 *
 * 【搜索原理】
 *   灰度模块在丢线时会把位置固定为"最后一次偏离方向的满幅值"
 *   （见 Gray.c 里的 GRAY_LOST_ERROR_FACTOR），
 *   所以 pd->error 的符号就代表了线最后在哪一边，用它决定转向。
 *
 *   搜索动作用"原地转"而不是"往前开"：
 *     外侧轮 +LINE_SEARCH_SPEED_CMS
 *     内侧轮 -LINE_SEARCH_SPEED_CMS × LINE_SEARCH_INNER_RATIO
 *   这样车绕着自身中心转，不会跑出赛道范围。
 *   如果改成往前开，车会越走越远，反而更找不回来。
 *
 * 【为什么必须限时】
 *   如果线真的没了（冲出赛道、压到桌边），无限搜索会让车一直转下去。
 *   超时后强制停车是最安全的兜底。
 */
/*
 * 搜索方向锁存。
 *
 * 【只用实测数据，不做推理】
 *
 *   方向 = 进入搜索那一拍 pd->error 的符号。
 *   而丢线期间 error 是 Gray 模块给出的"最后一次有效位置"的满幅回退值，
 *   所以这个符号直接来自传感器最后一次真实的测量，不是猜测。
 *
 *   曾经试过用"位置变化趋势"来预判急弯方向，但那个符号从未实测验证过，
 *   实际表现是"不管什么弯都往同一侧转"—— 这正是没有数据依据的行为，
 *   已删除。
 *
 * 【方向错了怎么办】
 *   由 LINE_SEARCH_BIDIRECTIONAL 兜底：先按锁存方向转一段，
 *   没找到就自动反方向再转一段。这样即使方向判断错，
 *   最多多花一段时间，不会彻底丢线。
 */
#define LINE_RECOVER_CYCLES         2U

/*
 * 搜索方向判定所需的最小信息量，单位 cm。
 *
 * 只有最后一次有效位置 |last_valid| 超过这个值，才认为
 * "车确实偏在线的一侧"，朝那一侧搜索才有数据依据。
 *
 * 低于这个值时说明线原本就在正中间（或者从未看到过线），
 * 我们【没有任何信息】判断它往哪边跑了 —— 此时不搜、直接停车。
 *
 * 0.5cm 的依据：通道间距 7mm，半个通道以内的位置无法可靠区分方向，
 * 取 0.5cm 略大于半个通道。
 */
#define LINE_SEARCH_MIN_INFO_CM     0.5f

/*
 * 没有任何方向信息时，搜索的【起始方向】。
 *
 * 这【不是】"猜测线往哪边跑了"，而是系统性扫描的起点：
 * 双向扫描会先按这个方向转 LINE_SEARCH_TIMEOUT_MS，
 * 找不到再反向转同样时间 —— 两个方向最终都会覆盖。
 *
 * 所以这个值只影响"先扫到哪一边"，
 * 不影响"能不能找到线"（除非在超时前就该放弃）。
 *
 * 设 +1 先向左，-1 先向右。
 */
#define LINE_SEARCH_DEFAULT_DIR     (-1)

/* ========================================================================= */
/* 场景响应（弯道识别后的动作）                                                */
/* ========================================================================= */

/*
 * 四种场景，各自的响应策略。
 *
 * 判据全部来自 Gray 的 scene 字段（可观测的通道状态），不含推断。
 */

/*
 * ---- ALL：几乎全部通道激活 ----
 *
 * 出现在三种场合：横向黑线、赛道终点标记、传感器悬空（离开赛道）。
 *
 * 【当前设 0：先关掉，等测速时再启用】
 *   关掉之后 ALL 场景只做记录（sc=ALL 仍然可以在串口看到），
 *   不改变车辆行为 —— 车会按正常 PD 继续跑。
 *
 *   这样做的原因：
 *     测速和调循迹参数阶段不希望"某个瞬间全亮"导致车突然停下，
 *     那种停机会掩盖真正的调参效果，也容易误判成故障。
 *
 * 【什么时候改成 1】
 *   等要做"终点自动停车"功能时再开。
 *   启用后注意：赛道上的十字交叉（横向线）也会触发停车，
 *   如果你的赛道有交叉，需要额外用条件区分（目前没有）。
 */
#define LINE_STOP_ON_ALL_BLACK      0

/* 判定 ALL 需要连续多少拍，避免单帧噪声误触发 */
#define LINE_ALL_CONFIRM_CYCLES     2U

/*
 * ---- SIDE：某半边的 4 路全黑 ----
 *
 * 直角弯。此时误差已经很大，正常 PD 也会给大差速，
 * 但这一帧的信息更明确（整半边都是线），所以额外做两件事：
 *   ① 更狠地减速（乘下面这个系数）
 *   ② 允许更大的差速（临时放宽到 diff_limit × 这个倍数）
 */
#define LINE_SIDE_SLOW_FACTOR       0.45f
#define LINE_SIDE_DIFF_BOOST        1.35f

/* 判定 SIDE 需要连续多少拍 */
#define LINE_SIDE_CONFIRM_CYCLES    2U

/*
 * ---- FORK：分叉 ----
 *
 * 锐角弯。记录 en corner_dir（见过的最新的分叉方向），
 * 丢线时优先用它决定搜索方向 —— 这是直接观测到的，
 * 比"最后一刻位置的符号"可靠。
 */
#define LINE_FORK_HOLD_CYCLES       15U

/*
 * 双向扫描。
 *
 * 【为什么需要】
 *   锐角弯丢线时，车往往已经冲过了弯。此时传感器"最后看到线的方向"
 *   会被过冲主导 —— 比如冲过左弯后线落在车的右侧，
 *   于是搜索往右转，正好是弯道外侧，越转越远。
 *
 *   这不是符号写错，而是"跟着最后位置转"这个启发式在急弯里
 *   原理上就不可靠（过冲量可能大于弯道本身的偏转）。
 *
 * 【做法】
 *   先用锁存方向转 LINE_SEARCH_TIMEOUT_MS；
 *   没找到就换成反方向再转同样长时间；
 *   还没找到才停车。
 *
 *   最坏情况耗时翻倍，但无论初始方向猜对猜错，都能覆盖 360°，
 *   一定能扫到线。对锐角弯这种"猜方向本来就不靠谱"的场景，
 *   用时间来换可靠性是值得的。
 *
 * 设 0 则退回单方向搜索（快但方向可能错）。
 */
#define LINE_SEARCH_BIDIRECTIONAL   1

/* ========================================================================= */
/* 车辆几何                                                                    */
/* ========================================================================= */

/*
 * 左右轮中心距（轮距），单位 cm。实测 16.0。
 *
 * 【用途】
 *   差速 -> 偏航角速度的换算：  omega = (v_right - v_left) / TRACK_WIDTH
 *   搜索转角、弯道所需差速等所有转向推算都基于它。
 *
 * 【为什么必须实测】
 *   曾经按 15cm 估算，导致理论转角比实际大 6%（1200ms 算出 220 度，
 *   实际只有 206 度），调整搜索时间时一直在往上加却总差一点。
 *
 * 【当前几何下的换算表】
 *   纯原地转（外侧 +24 / 内侧 -24）：omega = 48/16 = 3.0 rad/s = 172 度/秒
 *   每拍（外环 40ms）转 6.9 度，这是调搜索时间的粒度。
 *
 *     700ms -> 120 度
 *    1000ms -> 172 度
 *    1160ms -> 199 度
 *    1200ms -> 206 度
 *    1240ms -> 213 度
 *    1360ms -> 234 度
 */
#define LINE_TRACK_WIDTH_CM         16.0f

#define LINE_SEARCH_ENABLE          1

/*
 * 搜索最长时间，单位 ms（双向扫描时是【每一段】的时间）。
 *
 * 【当前取值 1200ms = 206 度】（按实测轮距 16cm 计算）
 *
 *   纯原地转（INNER_RATIO=1.0）的偏航角速度
 *       = (24 + 24) / 16cm = 3.0 rad/s = 172 度/秒
 *   每拍（外环 40ms）转 6.9 度 —— 调整的最小粒度。
 *
 *   演进过程（前几个数值是按错误的 15cm 算的，仅供参考趋势）：
 *      700ms  方向对但角度不够
 *     1100ms  还差约 20 度
 *     1240ms  略多，减 10 度
 *     1200ms  当前，实测（轮距 16cm）约 206 度
 *
 * 【调整方法】
 *   目标转角 D（度） -> TIMEOUT_ms = D / 172 * 1000
 *   只能取到 40ms 的整数倍（6.9 度粒度）。
 */
#define LINE_SEARCH_TIMEOUT_MS      1200U

/*
 * 搜索时的外侧轮速度，单位 cm/s。
 * 太快会转得猛、看不清线；太慢传感器采样时线几乎不动。
 * 10~18 之间比较合适。
 */
/*
 * 搜索时的外侧轮速度，单位 cm/s。
 *
 * 【从 14 提到 24 的原因：扫掠时间占了全部延迟的 90%】
 *
 *   直角弯的时间分解（容差 3 拍、轮距 15cm）：
 *     确认丢线      120ms   ( 10% )
 *     原地扫过 90 度 1086ms  ( 90% )  <- 瓶颈在这里
 *     合计          1206ms
 *
 *   偏航角速度 = (外侧 + 内侧反转) / 轮距
 *     14 cm/s -> 83 度/秒  -> 扫 90 度要 1.09 秒
 *     24 cm/s -> 142 度/秒 -> 扫 90 度只要 0.63 秒
 *
 * 【为什么 24 不会"转太快漏掉线"】
 *   以 142 度/秒算，外环 40ms 一拍转 5.7 度。
 *   传感器 49mm 阵列在约 30mm 距离上对应的张角约 78 度，
 *   扫过它需要约 14 个采样点，完全够传感器反应。
 *
 *   如果确实出现"转过去了但没认出来"，先降到 18~20 试试。
 */
#define LINE_SEARCH_SPEED_CMS       24.0f

/*
 * 搜索时内侧轮的反转比例（相对外侧轮速度）。
 * 0 = 内侧轮不转（绕内侧轮转，半径大）
 * 1 = 内外等速反转（绕自身中心原地转）
 *
 * 取 0.55 让转向中心略微偏向内侧轮，转弯半径小但仍有前进分量，
 * 有利于贴着弯道扫到线。
 */
/*
 * 搜索时内侧轮的反转比例（相对外侧轮速度）。
 *
 *   0    = 内侧轮不转 -> 绕内侧轮转，车会往前跑一大圈
 *   0.55 = 内侧轮半速反转 -> 有小幅前进分量（曾经用这个）
 *   1.0  = 内外等速反向 -> 【绕自身中心原地转】
 *
 * 【为什么改成 1.0】
 *   用 0.55 时，车的中心速度 = (外侧 - 内侧)/2 = (24 - 13.2)/2 ≈ 5.4 cm/s
 *   一直在往前爬。转 1.2 秒就爬出去 6cm 多 —— 正好爬到"身后的那条线"上，
 *   于是车头朝后、线在视野里，就沿着线往回跑了。
 *
 *   改成等速反转后，车绕自身中心旋转，位置基本不动，
 *   只改变朝向，不会无意中碰到别的线段。
 */
#define LINE_SEARCH_INNER_RATIO     1.0f

/*
 * 连续多少个外环周期没看到线，才判定为"真丢线"并进入搜索。
 *
 * 【从 3 降到 2 的原因】
 *   每个周期 40ms，3 拍就是 120ms。
 *   这段时间车仍在按原速前进，弦角弯时已经冲出去好几厘米。
 *   降到 2 拍（80ms）能少冲 40ms 的距离。
 *
 * 【为什么不敢降到 1】
 *   灰度偶尔会有单拍抖动（反光、接缝），1 拍就切搜索会误判，
 *   车会在直道上莫名其妙原地打转。2 拍是安全的下限。
 */
#define LINE_LOST_TOLERANCE         2U

/*
 * 丢线超时后是否停车。
 *
 *   1 = 停车（**初次调试务必用这个**）
 *       丢线就停，车不会冲出赛道，你也能立刻发现"传感器没看到线"。
 *
 *   0 = 继续转向搜索
 *       按灰度模块给出的"最后偏离方向"继续满舵前进，尝试找回线。
 *       适合调试完成后的实跑，但线丢得远时车会一直转圈。
 */
#define LINE_STOP_IF_LINE_LOST      1

/* ------------------------------------------------------------------------- */
/* 控制器结构体                                                                */
/* ------------------------------------------------------------------------- */

typedef struct
{
    /* ---- 可调参数 ---- */
    float kp;               /* 比例增益，单位 cm/s 差速量 每 cm 误差          */
    float kd;               /* 微分增益，单位 cm/s 差速量 每 (cm/s) 误差变化率 */
    float base_speed;       /* 基础速度，cm/s                                 */
    float diff_limit;       /* 差速量限幅，cm/s                               */
    float speed_limit;      /* 目标速度限幅，cm/s                             */
    float d_filter;         /* 微分低通系数 (0,1]                             */

    /* ---- 运行状态：由 Init/Reset 维护 ---- */
    float   error;          /* 最近一次误差，cm（左正右负）                   */
    float   last_error;     /* 上一次误差，用于求微分                          */
    float   d_filter_state; /* 微分项滤波状态                                 */
    float   steer;          /* 最近一次差速量，cm/s                           */
    float   speed;          /* 最近一次的目标基础速度，cm/s                   */

    /*
     * ---- 输出：左右轮的目标速度，cm/s ----
     *
     * 【为什么要在这里存一份，而不是直接调用 Speed_PID_Update】
     *
     *   外环和必须内环跑在不同的周期上：
     *     外环（循迹 PD）  100ms 一次 —— 读传感器、算差速
     *     内环（速度 PID）  20ms 一次 —— 比对编码器、调 PWM
     *
     *   如果外环里直接调 Speed_PID_Update，那么整个系统里
     *   唯一驱动速度环的地方就是外环，速度环也被拖到 100ms，
     *   比设计值慢 5 倍。轮子来不及跟到目标速度，差速就是错的，
     *   循迹会表现为"稍微一点弯就跟不住、直接偏离"。
     *
     *   正确做法：外环只把目标写进这两个字段，
     *   内环节拍每 20ms 读一次并调用 Speed_PID_Update，
     *   两个环各跑各的周期，互不牵制。
     */
    float   left_target;    /* 左轮目标速度，cm/s，由外环写入、内环读取      */
    float   right_target;   /* 右轮目标速度，cm/s                            */
    uint8_t lost_count;     /* 连续丢线周期数                                 */
    uint8_t line_lost;      /* 1 = 本次判定为丢线                             */
    uint16_t search_ms;     /* 已进入搜索状态的累计时间，ms；找到线后清零     */

    /*
     * ---- 搜索方向锁存与趋势判定 ----
     * search_dir    : 进入搜索时锁定的方向（+1 左 / -1 右 / 0 未锁定）
     * recover_count : 连续看到线的周期数，用于确认"真的找回来了"
     */
    int8_t   search_dir;
    uint8_t  recover_count;

    /*
     * ---- 场景响应状态 ----
     * all_count  : ALL 场景连续出现拍数（用于确认终点）
     * side_count : SIDE 场景连续出现拍数
     * side_dir   : SIDE 的方向（+1 左 / -1 右）
     * fork_dir   : FORK 观测到的弯道方向（+1 左 / -1 右 / 0 无）
     * fork_hold  : fork_dir 还要保留多少拍
     * scene_last : 上一拍得到的场景，便于边沿判断
     */
    uint8_t  all_count;
    uint8_t  side_count;
    int8_t   side_dir;
    int8_t   corner_dir;
    uint8_t  fork_hold;
    uint8_t  scene_last;

    uint8_t first_run;      /* 首拍标志，避免微分冲击                         */
} Line_PD_t;

