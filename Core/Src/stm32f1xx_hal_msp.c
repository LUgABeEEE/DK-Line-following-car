/**
  * @brief UART MSP Initialization
  * This function configures the hardware resources used in this example
  * @param huart: UART handle pointer
  * @retval None
  */
void HAL_UART_MspInit(UART_HandleTypeDef* huart)
{
  GPIO_InitTypeDef GPIO_InitStruct = {0};
  if(huart->Instance==USART2)
  {
    /* USER CODE BEGIN USART2_MspInit 0 */

    /* USER CODE END USART2_MspInit 0 */
    /* Peripheral clock enable */
    __HAL_RCC_USART2_CLK_ENABLE();

    __HAL_RCC_GPIOA_CLK_ENABLE();
    /**USART2 GPIO Configuration
    PA2     ------> USART2_TX
    PA3     ------> USART2_RX
    */
    GPIO_InitStruct.Pin = BLE_TX_Pin;
    GPIO_InitStruct.Mode = GPIO_MODE_AF_PP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(BLE_TX_GPIO_Port, &GPIO_InitStruct);

    /*
     * ⚠️ BLE_RX(PA3) 必须上拉，不能用 NOPULL。
     *
     * 比赛时蓝牙模块要拔掉（避免被误认为遥控）。拔掉后 PA3 悬空，
     * 浮空输入会拾取噪声，随机产生起始位 -> 收到乱码字节 ->
     * 而命令处理是【无条件】解析的（'X'/'S'/'Q' 都是急停），
     * 可能在跑车中途被噪声触发急停。
     *
     * 上拉之后空闲电平为高，噪声很难凑出一个完整的起始位 + 8 数据位
     * （9600 波特下要维持约 1ms 的低电平）。
     */
    GPIO_InitStruct.Pin = BLE_RX_Pin;
    GPIO_InitStruct.Mode = GPIO_MODE_INPUT;
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    HAL_GPIO_Init(BLE_RX_GPIO_Port, &GPIO_InitStruct);

    /* USART2 interrupt Init */
    HAL_NVIC_SetPriority(USART2_IRQn, 5, 0);
    HAL_NVIC_EnableIRQ(USART2_IRQn);
    /* USER CODE BEGIN USART2_MspInit 1 */

    /* USART2 全局中断使能——蓝牙模块(JDY-31)靠它做字节接收。
       在 CubeMX 里勾选 NVIC -> USART2 global interrupt 之后，这两行会被
       自动生成到 USER CODE 区之外，届时可以删掉这里的手工版本。
       优先级 5：与 ADC1_2 一致，数值上等于 FreeRTOS 的
       configMAX_SYSCALL_INTERRUPT_PRIORITY(5<<4)，将来如果启用 RTOS，
       在这个中断里调用带 FromISR 的 API 也不会触发 configASSERT。 */
    HAL_NVIC_SetPriority(USART2_IRQn, 5U, 0U);
    HAL_NVIC_EnableIRQ(USART2_IRQn);

    /* USER CODE END USART2_MspInit 1 */

  }

}

