  // BLE_TestSequence(10U);     /* 蓝牙状态监视：STAT 引脚与连接状态，10 秒 */

  /* 上车跑圈之前必须先跑这一行，把三个符号钉死（电机默认不动，安全） */
  // LinePD_VerifySigns(&g_line_pd, &g_gray, &hi2c1, 0);

